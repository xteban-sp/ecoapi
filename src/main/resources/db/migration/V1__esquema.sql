-- Esquema de EcoRecicla.
-- La autorizacion vive en la base: un rol es un conjunto de privilegios (rol_privilegio).
-- Agregar un rol o un privilegio es insertar filas aqui, no tocar controladores.

CREATE TABLE privilegio (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE rol (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE rol_privilegio (
    rol_id        BIGINT NOT NULL REFERENCES rol (id),
    privilegio_id BIGINT NOT NULL REFERENCES privilegio (id),
    PRIMARY KEY (rol_id, privilegio_id)
);

CREATE TABLE usuario (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(40)  NOT NULL UNIQUE,
    -- BCrypt: nunca se guarda la contrasena en claro
    password        VARCHAR(100) NOT NULL,
    nombre_completo VARCHAR(120) NOT NULL,
    rol_id          BIGINT       NOT NULL REFERENCES rol (id),
    activo          BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE punto_acopio (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social      VARCHAR(150) NOT NULL,
    direccion         VARCHAR(200) NOT NULL,
    zona              VARCHAR(40)  NOT NULL,
    material_habitual VARCHAR(40)  NOT NULL
);

CREATE TABLE ruta (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha         DATE        NOT NULL,
    operario_id   BIGINT      NOT NULL REFERENCES usuario (id),
    supervisor_id BIGINT      NOT NULL REFERENCES usuario (id),
    estado        VARCHAR(10) NOT NULL CHECK (estado IN ('ABIERTA', 'CERRADA')),
    cerrada_en    TIMESTAMP
);

-- Punto planificado dentro de una ruta, con su orden de visita.
CREATE TABLE ruta_punto (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruta_id        BIGINT       NOT NULL REFERENCES ruta (id),
    punto_id       BIGINT       NOT NULL REFERENCES punto_acopio (id),
    secuencia      INT          NOT NULL,
    -- RN-04: un punto sin pesaje solo deja cerrar la ruta si tiene motivo de omision
    motivo_omision VARCHAR(200),
    UNIQUE (ruta_id, punto_id),
    UNIQUE (ruta_id, secuencia)
);

CREATE TABLE pesaje (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruta_id          BIGINT        NOT NULL REFERENCES ruta (id),
    punto_id         BIGINT        NOT NULL REFERENCES punto_acopio (id),
    fecha_hora       TIMESTAMP     NOT NULL,
    material         VARCHAR(40)   NOT NULL,
    peso_bruto       DECIMAL(10,2) NOT NULL,
    tara             DECIMAL(10,2) NOT NULL,
    -- RN-03: lo calcula el servicio (bruto - tara) y debe ser > 0
    peso_neto        DECIMAL(10,2) NOT NULL CHECK (peso_neto > 0),
    observacion      VARCHAR(250)  NOT NULL DEFAULT '',
    operario_id      BIGINT        NOT NULL REFERENCES usuario (id),
    -- La anulacion no borra: marca
    anulado          BOOLEAN       NOT NULL DEFAULT FALSE,
    motivo_anulacion VARCHAR(200)
);

CREATE INDEX idx_pesaje_punto ON pesaje (punto_id, fecha_hora);
CREATE INDEX idx_pesaje_ruta ON pesaje (ruta_id);
